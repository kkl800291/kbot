/** 给某个点标上对位比例。 */
function at(points, marks) {
  return points.map(p => {
    const m = marks.find(([x, y]) => x === p[0] && y === p[1]);
    return m ? [p[0], p[1], m[2]] : [p[0], p[1]];
  });
}

